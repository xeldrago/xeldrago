#!/usr/bin/env python3
"""Builds the productivity data block and injects it into the games.

  productivity-packs/*.txt   one study pack per file  (Subject|Topic|Answer|Hint|Clue 1|Clue 2)
  <Kondattam page>.html      source of the general word lists (Imposter DB, Heads Up decks, 20Q lists)
  Hangman.template.html      Hangman with the /*__PROD_DATA__*/ placeholder

Outputs: Hangman.html and productivity-data.js
To add a new pack: drop another .txt file into productivity-packs/ (see the header lines of the existing one) and run this again.
"""
import json, glob, os, re, subprocess, sys, textwrap

BASE = os.path.dirname(os.path.abspath(__file__))
PACKS = sorted(glob.glob(os.path.join(BASE, 'productivity-packs', '*.txt')))
KONDATTAM = next((os.path.join(BASE, f) for f in ('FriendGroupGames.html', 'party-games.html') if os.path.exists(os.path.join(BASE, f))), None)

def read_pack(path):
    pid = os.path.splitext(os.path.basename(path))[0]
    title, source, items, seen = pid, '', [], set()
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip():
            continue
        if line.startswith('# pack:'):
            parts = [x.strip() for x in line[len('# pack:'):].split('|')]
            pid = parts[0] or pid
            title = parts[1] if len(parts) > 1 else title
            source = parts[2] if len(parts) > 2 else ''
            continue
        if line.startswith('#'):
            continue
        p = [x.strip() for x in line.split('|')]
        if len(p) != 6 or any(not x for x in p):
            sys.exit(f'{os.path.basename(path)} line {n}: need 6 non-empty parts, got {len(p)}')
        k = p[2].lower()
        if k in seen:
            print('  skipping duplicate answer:', p[2])
            continue
        seen.add(k)
        items.append(p)
    return {'id': pid, 'title': title, 'source': source, 'items': items}

def kondattam_general():
    if not KONDATTAM:
        print('  (no Kondattam page found - general words skipped)')
        return []
    html = open(KONDATTAM, encoding='utf-8').read()
    a = html.index('// ---------- data ----------'); b = html.index('// ---------- nav ----------')
    c = html.index('// ===== IMP-ENGINE-START ====='); d = html.index('// ===== IMP-ENGINE-END =====')
    js = ('const lists=new Function(%s)();const IMPDB=new Function(%s)();console.log(JSON.stringify({lists,IMPDB}));'
          % (json.dumps(html[a:b] + ';return {movies,words,malayalam,english,bible,anime};'),
             json.dumps(html[c:d] + ';return IMP_DB;')))
    out = subprocess.run(['node', '-e', js], capture_output=True, text=True)
    if out.returncode:
        sys.exit(out.stderr)
    data = json.loads(out.stdout)
    L, decks = data['lists'], []
    slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
    for c in data['IMPDB']:
        decks.append({'id': 'imp-' + slug(c['c']), 'group': 'Party words with hints', 'n': c['c'], 'e': c['e'],
                      'd': 'A word from the category ' + c['c'], 'w': [[x['w'], x['h']] for x in c['w']]})
    extra = [('deck-tamil', 'Tamil Movies (2015-now)', '🎬', 'A Tamil movie released between 2015 and now', L['movies']),
             ('deck-malayalam', 'Malayalam Movies (2015-now)', '🎞️', 'A Malayalam movie released between 2015 and now', L['malayalam']),
             ('deck-english', 'English Movies (1990-now)', '🍿', 'An English-language movie from 1990 onwards', L['english']),
             ('deck-bible', 'Biblical Names', '✝️', 'A name from the Bible', L['bible']),
             ('deck-anime', 'Anime (titles & characters)', '🍥', 'An anime title or character', L['anime']),
             ('deck-person', 'Famous People', '⭐', 'A famous person', L['words']['person']),
             ('deck-object', 'More Objects', '🔑', 'An everyday object', L['words']['object']),
             ('deck-animal', 'More Animals', '🐾', 'An animal or creature', L['words']['animal'])]
    for i, g, e, d, w in extra:
        decks.append({'id': i, 'group': 'Movies, people & more', 'n': g, 'e': e, 'd': d, 'w': w})
    return decks

packs = [read_pack(p) for p in PACKS]
decks = kondattam_general()
block = ('const PROD_PACKS=%s;\nconst GENERAL_DECKS=%s;\n'
         % (json.dumps(packs, ensure_ascii=False, separators=(',', ':')), json.dumps(decks, ensure_ascii=False, separators=(',', ':'))))
open(os.path.join(BASE, 'productivity-data.js'), 'w', encoding='utf-8').write('/* generated by build-productivity.py */\n' + block)
tpl = open(os.path.join(BASE, 'Hangman.template.html'), encoding='utf-8').read()
assert '/*__PROD_DATA__*/' in tpl
open(os.path.join(BASE, 'Hangman.html'), 'w', encoding='utf-8').write(tpl.replace('/*__PROD_DATA__*/', block.replace('</', '<\\/')))
print('packs:', [(p['id'], len(p['items'])) for p in packs])
print('general decks:', len(decks), 'with', sum(len(d['w']) for d in decks), 'words')
